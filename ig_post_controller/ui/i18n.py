LANGUAGE_OPTION_KEYS = {
    "en": "settings.language.en",
    "ko": "settings.language.ko",
    "ja": "settings.language.ja",
    "zh": "settings.language.zh",
}


@dataclass(slots=True)
class LanguageOption:
    code: str
    label: str


class LanguageManager(QObject):
    language_changed = Signal(str)

    def __init__(self, language: str | None = None) -> None:
        super().__init__()
        self._language = normalize_app_language(language)

    @property
    def language(self) -> str:
        return self._language

    def set_language(self, language: str | None) -> str:
        normalized = normalize_app_language(language)
        if normalized == self._language:
            return self._language
        self._language = normalized
        self.language_changed.emit(self._language)
        return self._language

    def tr(self, key: str, **kwargs) -> str:
        template = TRANSLATIONS.get(self._language, TRANSLATIONS[DEFAULT_APP_LANGUAGE]).get(
            key,
            TRANSLATIONS["en"].get(key, key),
        )
        return template.format(**kwargs) if kwargs else template

    def language_options(self) -> list[LanguageOption]:
        return [LanguageOption(code=code, label=self.tr(label_key)) for code, label_key in LANGUAGE_OPTION_KEYS.items()]

    def language_label(self, code: str) -> str:
        normalized = normalize_app_language(code)
        return self.tr(LANGUAGE_OPTION_KEYS.get(normalized, LANGUAGE_OPTION_KEYS[DEFAULT_APP_LANGUAGE]))


def normalize_language_for_storage(value: str | None) -> str:
    return normalize_app_language(value)
